// Exports, from the mockup's own code, the inputs and the cost/price of every piece and collection.
// Output: packages/core/test/golden/mockup-values.json — the criterion of phase 2 (CLAUDE.md, tolerance ±0.01).
// Usage: node tools/export-mockup-golden.mjs
import { writeFileSync } from 'node:fs';
import { openMockup } from './mockup-page.mjs';

const { browser, page } = await openMockup();
const data = await page.evaluate(() => {
  const m = window.__mockup;
  const S = m.S;
  const pick = (o, ks) => Object.fromEntries(ks.map((k) => [k, o[k]]));
  const products = S.productos.map((p) => {
    const c = m.costo(p, null, S);
    const margin = m.margenDe(p, S);
    return {
      input: pick(p, ['id', 'nombre', 'imp', 'horas', 'extras', 'insumos', 'filamentos', 'precio', 'modo', 'margen', 'padre', 'lote']),
      expected: {
        M: c.M, L: c.L, Q: c.Q, E: c.E, sub: c.sub, F: c.F, cost: c.total,
        listPrice: m.precioDe(p, S),
        floor: m.piso(c.total, S),
        suggested: m.sugerido(c.total, Math.min(95, margin)),
        byChannel: S.config.canales.map((ch) => ({ channel: ch.n, commission: ch.c, suggested: m.sugerido(c.total, Math.min(95, margin), ch.c) })),
      },
    };
  });
  const collections = S.colecciones.map((col) => {
    const cc = m.costoCol(col, 1, S);
    return {
      input: pick(col, ['id', 'nombre', 'partes', 'extras', 'precio']),
      expected: { loose: m.sueltas(col, S), price: m.precioCol(col, S), pieces: cc.piezas, extras: cc.E, cost: cc.total, parts: cc.partes.map((x) => ({ product: x.prod, qty: x.cant, listPrice: x.lista, cost: x.costo })) },
    };
  });
  return {
    note: 'Generated by tools/export-mockup-golden.mjs from reference/Quick Robot mockup.html. Do not edit by hand.',
    config: { kwh: S.config.kwh, failurePct: S.config.fallos, purgePct: S.config.purga, minMarginPct: S.config.margenMin, formulaMarginPct: S.config.margenFormula, channels: S.config.canales },
    filaments: S.filamentos.map((f) => ({ id: f.id, material: f.material, color: f.color, costPerGram: m.costoGF(f.id, S) })),
    spools: S.rollos.map((r) => ({ id: r.id, filament: r.fil, cost: r.costo, shipping: r.envio, grams: r.gramos, purchasedOffsetDays: Math.round((new Date(r.fecha + 'T12:00:00') - new Date(new Date().setHours(12, 0, 0, 0))) / 864e5), remaining: m.restante(r, S) })),
    printers: S.impresoras.map((i) => pick(i, ['id', 'nombre', 'costo', 'vidaH', 'mantoH', 'kw', 'horas'])),
    supplies: S.insumos.map((i) => ({ ...pick(i, ['id', 'nombre', 'unidad', 'costo', 'minimo']), stock: m.stockIns(i.id, S) })),
    products,
    collections,
  };
});
await browser.close();
writeFileSync('packages/core/test/golden/mockup-values.json', JSON.stringify(data, null, 2) + '\n');
console.log(`golden: ${data.products.length} products, ${data.collections.length} collections`);
